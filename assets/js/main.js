const body = document.body;
const pageShell = document.querySelector(".page-shell");
const menuToggle = document.querySelector("[data-menu-toggle]");
const mobileMenu = document.querySelector("[data-mobile-menu]");
const languageSwitcher = document.querySelector("[data-language-switcher]");
const languageTrigger = document.querySelector("[data-language-trigger]");
const currentLanguage = document.querySelector("[data-current-language]");
const languageButtons = document.querySelectorAll("[data-language]");
const i18nNodes = document.querySelectorAll("[data-i18n]");
const cookieTrigger = document.querySelector("[data-cookie-trigger]");
const cookieModal = document.querySelector("[data-cookie-modal]");
const cookieClose = document.querySelector("[data-cookie-close]");
const imprintTrigger = document.querySelector("[data-imprint-trigger]");
const imprintModal = document.querySelector("[data-imprint-modal]");
const imprintClose = document.querySelector("[data-imprint-close]");
const imageTriggers = document.querySelectorAll("[data-image-trigger]");
const imageModal = document.querySelector("[data-image-modal]");
const imagePreview = document.querySelector("[data-image-preview]");
const imageCaption = document.querySelector("[data-image-caption]");
const imageClose = document.querySelector("[data-image-close]");

const languageStorageKey = "rayven-language";
const storedLanguage = window.localStorage.getItem(languageStorageKey);
let activeLanguage = translations[storedLanguage] ? storedLanguage : "de";

const applyTranslations = (language) => {
	const dictionary = translations[language];

	i18nNodes.forEach((node) => {
		const path = node.dataset.i18n.split(".");
		const value = path.reduce((entry, key) => entry && entry[key], dictionary);

		if (value) {
			node.textContent = value;
		}
	});

	currentLanguage.textContent = language === "ja" ? "JP" : language.toUpperCase();

	languageButtons.forEach((button) => {
		button.classList.toggle("is-active", button.dataset.language === language);
	});

	document.documentElement.lang = language;
	activeLanguage = language;
	window.localStorage.setItem(languageStorageKey, language);
};

const closeLanguageMenu = () => {
	languageSwitcher.classList.remove("is-open");
	languageTrigger.setAttribute("aria-expanded", "false");
};

const toggleLanguageMenu = () => {
	const isOpen = languageSwitcher.classList.toggle("is-open");
	languageTrigger.setAttribute("aria-expanded", String(isOpen));
};

const setCookieModalState = (isOpen) => {
	cookieModal.classList.toggle("is-open", isOpen);
	cookieModal.setAttribute("aria-hidden", String(!isOpen));
	if (isOpen) {
		cookieClose.focus();
	}
};

const setImprintModalState = (isOpen) => {
	imprintModal.classList.toggle("is-open", isOpen);
	imprintModal.setAttribute("aria-hidden", String(!isOpen));
	if (isOpen) {
		imprintClose.focus();
	}
};

const setImageModalState = (isOpen, trigger = null) => {
	if (!imageModal) {
		return;
	}

	if (isOpen && trigger) {
		const image = trigger.querySelector("img");
		const caption = trigger.querySelector("figcaption");
		imagePreview.src = image.src;
		imagePreview.alt = image.alt;
		imageCaption.textContent = caption.textContent;
		imageModal.classList.add("is-open");
		imageModal.setAttribute("aria-hidden", "false");
		imageClose.focus();
		return;
	}

	imageModal.classList.remove("is-open");
	imageModal.setAttribute("aria-hidden", "true");
};

const setMenuState = (isOpen) => {
	body.classList.toggle("menu-open", isOpen);
	pageShell.classList.toggle("menu-open", isOpen);
	mobileMenu.setAttribute("aria-hidden", String(!isOpen));
	menuToggle.setAttribute("aria-expanded", String(isOpen));
	menuToggle.setAttribute("aria-label", isOpen ? "Menü schließen" : "Menü öffnen");
	if (isOpen) {
		closeLanguageMenu();
	}
};

menuToggle.addEventListener("click", () => {
	setMenuState(!body.classList.contains("menu-open"));
});

mobileMenu.querySelectorAll("a").forEach((link) => {
	link.addEventListener("click", () => setMenuState(false));
});

languageTrigger.addEventListener("click", toggleLanguageMenu);

languageButtons.forEach((button) => {
	button.addEventListener("click", () => {
		applyTranslations(button.dataset.language);
		closeLanguageMenu();
	});
});

document.addEventListener("click", (event) => {
	if (!languageSwitcher.contains(event.target)) {
		closeLanguageMenu();
	}
});

document.addEventListener("keydown", (event) => {
	if (event.key === "Escape") {
		closeLanguageMenu();
		setMenuState(false);
		setCookieModalState(false);
		setImprintModalState(false);
		setImageModalState(false);
	}
});

cookieTrigger.addEventListener("click", () => setCookieModalState(true));
cookieClose.addEventListener("click", () => setCookieModalState(false));
cookieModal.addEventListener("click", (event) => {
	if (event.target === cookieModal) {
		setCookieModalState(false);
	}
});

imprintTrigger.addEventListener("click", (event) => {
	event.preventDefault();
	setImprintModalState(true);
});
imprintClose.addEventListener("click", () => setImprintModalState(false));
imprintModal.addEventListener("click", (event) => {
	if (event.target === imprintModal) {
		setImprintModalState(false);
	}
});

imageTriggers.forEach((trigger) => {
	trigger.addEventListener("click", () => setImageModalState(true, trigger));
	trigger.addEventListener("keydown", (event) => {
		if (event.key === "Enter" || event.key === " ") {
			event.preventDefault();
			setImageModalState(true, trigger);
		}
	});
});

if (imageModal) {
	imageClose.addEventListener("click", () => setImageModalState(false));
	imageModal.addEventListener("click", (event) => {
		if (event.target === imageModal) {
			setImageModalState(false);
		}
	});
}

setMenuState(false);
applyTranslations(activeLanguage);

if (window.lucide) {
	window.lucide.createIcons();
}
